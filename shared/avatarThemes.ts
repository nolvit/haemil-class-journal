export const avatarThemePresets = Object.fromEntries(
  avatarThemes.map(theme => [
    theme,
    rows[theme].map((v, i) => make(theme, i, v)),
  ])
) as Record<AvatarTheme, Preset[]>;
export function chooseThemePreset(theme: AvatarTheme, random = Math.random) {
  return avatarThemePresets[theme][Math.min(4, Math.floor(random() * 5))];
}
